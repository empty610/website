// Keep editable sources separate while serving one render-blocking request.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const home = path.join(root, 'home');
const sources = ['style.css', 'solar-entry.css', 'navigation.css'];
const css = sources.map(file => fs.readFileSync(path.join(home, file), 'utf8').replace(/\r\n/g, '\n')).join('\n');
const output = '/* Generated by scripts/build-home-css.cjs */\n' + css;
const target = path.join(home, 'home.css');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('home/home.css 与源样式不一致，请运行 npm run build:css。');
    process.exitCode = 1;
  } else console.log('主页样式产物一致性检查通过。');
} else fs.writeFileSync(target, output);
