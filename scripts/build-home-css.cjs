// Keep editable sources separate while serving one render-blocking request.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const home = path.join(root, 'home');
const sources = ['style.css', 'venus-entry.css', 'mars-entry.css', 'navigation.css'];
const css = sources.map(file => fs.readFileSync(path.join(home, file), 'utf8')).join('\n');
fs.writeFileSync(path.join(home, 'home.css'), '/* Generated by scripts/build-home-css.cjs */\n' + css);
